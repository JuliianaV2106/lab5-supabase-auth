/// Root widget that declares the theme and the named routes.
class App extends StatelessWidget {
  const App({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Moviles Auth',
      debugShowCheckedModeBanner: false,
      theme: buildTheme(),
      initialRoute: '/login',
      routes: {
        '/login': (_) => BlocProvider(
          create: (_) => LoginBloc(
            SignInUseCase(
              AuthRepositoryImpl(
                SupabaseAuthDataSource(Supabase.instance.client),
              ),
              ProfileRepositoryImpl(
                SupabaseProfileDataSource(Supabase.instance.client),
              ),
            ),
          ),
          child: const LoginScreen(),
        ),
        '/register': (_) => BlocProvider(
          create: (_) => RegisterBloc(
            SignUpUseCase(
              AuthRepositoryImpl(
                SupabaseAuthDataSource(Supabase.instance.client),
              ),
              ProfileRepositoryImpl(
                SupabaseProfileDataSource(Supabase.instance.client),
              ),
            ),
          ),
          child: const RegisterScreen(),
        ),
        '/home': (context) {
          final args =
              ModalRoute.of(context)!.settings.arguments
                  as ({Profile profile, String email});
          return BlocProvider(
            create: (_) => HomeBloc(
              SignOutUseCase(
                AuthRepositoryImpl(
                  SupabaseAuthDataSource(Supabase.instance.client),
                ),
              ),
            ),
            child: HomeScreen(
              username: args.profile.username,
              fullName: args.profile.fullName,
              email: args.email,
            ),
          );
        },
      },
    );
  }
}
